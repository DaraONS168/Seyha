create or replace function public.prepare_mission_expense() returns trigger language plpgsql security definer set search_path=public as $$
declare plan_row public.visit_plans;
begin
  if new.visit_plan_id is null then return new; end if;
  select * into plan_row from public.visit_plans where id=new.visit_plan_id;
  if plan_row.id is null then raise exception 'Visit plan not found'; end if;
  if plan_row.status='cancelled' then raise exception 'Cancelled visit plan cannot have an expense request'; end if;
  new.sales_id := plan_row.assigned_to;
  new.estimated_distance_km := coalesce(plan_row.planned_distance_km,new.estimated_distance_km,0);
  if new.request_date<plan_row.start_date or new.request_date>plan_row.end_date then new.request_date:=plan_row.start_date; end if;
  new.settlement_due_date := coalesce(new.settlement_due_date,plan_row.end_date+7);
  return new;
end $$;
create trigger expense_requests_prepare_mission before insert or update of visit_plan_id,request_date on public.expense_requests for each row execute function public.prepare_mission_expense();

create or replace function public.estimate_mission_expense(p_visit_plan_id uuid,p_participant_count integer default 1)
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare plan_row public.visit_plans; mission_days integer; mission_nights integer; distance_km numeric; transport numeric; meals numeric; lodging numeric; other_amount numeric;
begin
  if not public.can_access_visit_plan(p_visit_plan_id) and not public.has_permission('expenses.view') then raise exception 'Access denied'; end if;
  select * into plan_row from public.visit_plans where id=p_visit_plan_id;
  if plan_row.id is null then raise exception 'Visit plan not found'; end if;
  mission_days:=plan_row.end_date-plan_row.start_date+1; mission_nights:=greatest(mission_days-1,0); p_participant_count:=greatest(p_participant_count,1);
  select coalesce(plan_row.planned_distance_km, sum(segment_km)*2, 0) into distance_km from (
    select 6371*acos(least(1,greatest(-1,cos(radians(latitude))*cos(radians(previous_latitude))*cos(radians(previous_longitude)-radians(longitude))+sin(radians(latitude))*sin(radians(previous_latitude))))) as segment_km
    from (select latitude,longitude,lag(latitude) over(order by stop_order) as previous_latitude,lag(longitude) over(order by stop_order) as previous_longitude from public.visit_plan_stops where visit_plan_id=p_visit_plan_id and latitude is not null and longitude is not null) stops
    where previous_latitude is not null
  ) distances;
  select coalesce(rate,0)*distance_km into transport from public.mission_expense_rates where code='transport_km' and is_active;
  select coalesce(rate,0)*p_participant_count*mission_days into meals from public.mission_expense_rates where code='meal_person_day' and is_active;
  select coalesce(rate,0)*p_participant_count*mission_nights into lodging from public.mission_expense_rates where code='lodging_person_night' and is_active;
  select coalesce(rate,0) into other_amount from public.mission_expense_rates where code='mission_other' and is_active;
  return jsonb_build_object('days',mission_days,'nights',mission_nights,'distance_km',distance_km,'participants',p_participant_count,'transport',coalesce(transport,0),'meals',coalesce(meals,0),'lodging',coalesce(lodging,0),'other',coalesce(other_amount,0),'total',coalesce(transport,0)+coalesce(meals,0)+coalesce(lodging,0)+coalesce(other_amount,0));
end $$;

create or replace view public.sales_mission_expense_summary with (security_invoker=true) as
select request.sales_id,sales.full_name as sales_name,count(*) as request_count,
  coalesce(sum(request.approved_amount),0) as approved_amount,coalesce(sum(request.amount_received),0) as paid_amount,
  coalesce(sum(request.actual_amount),0) as actual_amount,coalesce(sum(request.returned_amount),0) as returned_amount,
  count(*) filter(where request.status in ('submitted','under_review','approved','payment_processing','paid')) as active_missions,
  count(*) filter(where request.status='completed') as completed_missions
from public.expense_requests request join public.profiles sales on sales.id=request.sales_id
where request.deleted_at is null and request.sales_id is not null group by request.sales_id,sales.full_name;

