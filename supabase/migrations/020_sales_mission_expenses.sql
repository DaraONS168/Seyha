create table public.mission_expense_rates (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name_kh text not null,
  unit text not null check (unit in ('km','person_day','person_night','flat')),
  rate numeric(16,2) not null check (rate >= 0),
  is_active boolean not null default true,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger mission_expense_rates_updated_at before update on public.mission_expense_rates for each row execute function public.set_updated_at();

