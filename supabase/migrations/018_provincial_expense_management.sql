create or replace function public.prepare_expense_request() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.request_code := 'EXP-' || extract(year from new.request_date)::integer || '-' || lpad(nextval('public.expense_request_code_sequence')::text, 6, '0');
    new.requested_by := auth.uid(); new.created_by := auth.uid();
  else
    new.request_code := old.request_code; new.requested_by := old.requested_by; new.updated_by := auth.uid();
    if old.status = 'completed' and not public.has_permission('expenses.reopen') then raise exception 'Completed expense is locked'; end if;
    if old.status not in ('draft','returned') and row(new.request_date,new.province_id,new.project_id,new.expense_category_id,new.purpose,new.requested_amount)
      is distinct from row(old.request_date,old.province_id,old.project_id,old.expense_category_id,old.purpose,old.requested_amount) then
      raise exception 'Only draft or returned requests can be edited';
    end if;
  end if;
  return new;
end $$;
create trigger expense_requests_prepare before insert or update on public.expense_requests for each row execute function public.prepare_expense_request();

create or replace function public.expense_scope_allows(p_province_id bigint) returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and is_active and (role = 'admin' or province_id is null or province_id = p_province_id));
$$;

create or replace function public.available_budget(p_province_id bigint, p_project_id bigint, p_category_id bigint, p_fiscal_year integer)
returns numeric language sql stable security definer set search_path = public as $$
  select coalesce((select remaining_amount from public.provincial_budgets
    where province_id=p_province_id and project_id=p_project_id and expense_category_id=p_category_id
      and fiscal_year=p_fiscal_year and status='active'),0);
$$;

create or replace function public.submit_expense_request(p_request_id uuid) returns public.expense_requests
language plpgsql security definer set search_path = public as $$
declare request_row public.expense_requests; budget_row public.provincial_budgets; result public.expense_requests; rule_count integer;
begin
  if not public.has_permission('expenses.submit') then raise exception 'Access denied'; end if;
  select * into request_row from public.expense_requests where id=p_request_id and deleted_at is null for update;
  if request_row.requested_by <> auth.uid() or request_row.status not in ('draft','returned') then raise exception 'Request cannot be submitted'; end if;
  select * into budget_row from public.provincial_budgets where fiscal_year=extract(year from request_row.request_date)::integer
    and province_id=request_row.province_id and project_id=request_row.project_id and expense_category_id=request_row.expense_category_id and status='active' for update;
  if budget_row.id is null then raise exception 'No active budget found'; end if;
  if request_row.requested_amount > budget_row.remaining_amount then
    raise exception 'Budget exceeded. Available: %, Requested: %, Exceeded: %', budget_row.remaining_amount, request_row.requested_amount, request_row.requested_amount-budget_row.remaining_amount;
  end if;
  delete from public.expense_approvals where expense_request_id=p_request_id;
  insert into public.expense_approvals(expense_request_id,approval_level,approver_role)
  select p_request_id,approval_level,approver_role from public.approval_rules
  where is_active and request_row.requested_amount >= min_amount and (max_amount is null or request_row.requested_amount <= max_amount)
  order by approval_level;
  get diagnostics rule_count = row_count;
  if rule_count=0 then raise exception 'No approval rule configured for this amount'; end if;
  update public.expense_requests set status='submitted',submitted_at=now(),updated_by=auth.uid() where id=p_request_id returning * into result;
  return result;
end $$;

create or replace function public.decide_expense_request(p_request_id uuid,p_decision text,p_comment text default null,p_approved_amount numeric default null)
returns public.expense_requests language plpgsql security definer set search_path = public as $$
declare request_row public.expense_requests; approval_row public.expense_approvals; result public.expense_requests; pending_count integer; actor_role text;
begin
  if not public.has_permission('expenses.approve') then raise exception 'Access denied'; end if;
  if p_decision not in ('approved','rejected','returned') then raise exception 'Invalid decision'; end if;
  select role into actor_role from public.profiles where id=auth.uid();
  select * into request_row from public.expense_requests where id=p_request_id and deleted_at is null for update;
  if request_row.requested_by=auth.uid() then raise exception 'Requester cannot approve own request'; end if;
  select * into approval_row from public.expense_approvals where expense_request_id=p_request_id and decision='pending'
    order by approval_level limit 1 for update;
  if approval_row.id is null then raise exception 'No pending approval'; end if;
  if actor_role<>'admin' and approval_row.approver_role<>actor_role then raise exception 'This approval level requires role %',approval_row.approver_role; end if;
  if p_decision in ('rejected','returned') and char_length(trim(coalesce(p_comment,'')))<3 then raise exception 'Comment is required'; end if;
  update public.expense_approvals set decision=p_decision,comment=nullif(trim(p_comment),''),approver_id=auth.uid(),action_date=now() where id=approval_row.id;
  if p_decision='rejected' then update public.expense_requests set status='rejected',updated_by=auth.uid() where id=p_request_id returning * into result; return result; end if;
  if p_decision='returned' then update public.expense_requests set status='returned',updated_by=auth.uid() where id=p_request_id returning * into result; return result; end if;
  select count(*) into pending_count from public.expense_approvals where expense_request_id=p_request_id and decision='pending';
  if pending_count>0 then update public.expense_requests set status='under_review',updated_by=auth.uid() where id=p_request_id returning * into result;
  else
    result.approved_amount := least(coalesce(p_approved_amount,request_row.requested_amount),request_row.requested_amount);
    update public.provincial_budgets set committed_amount=committed_amount+result.approved_amount,updated_by=auth.uid()
      where fiscal_year=extract(year from request_row.request_date)::integer and province_id=request_row.province_id and project_id=request_row.project_id and expense_category_id=request_row.expense_category_id;
    update public.expense_requests set status='approved',approved_amount=result.approved_amount,approved_at=now(),updated_by=auth.uid() where id=p_request_id returning * into result;
  end if;
  return result;
end $$;

create or replace function public.create_expense_payment(p_request_id uuid,p_payment_date date,p_method text,p_amount numeric,p_bank_name text,p_reference text,p_recipient text,p_attachment text)
returns public.expense_payments language plpgsql security definer set search_path = public as $$
declare request_row public.expense_requests; paid_total numeric; payment public.expense_payments;
begin
  if not public.has_permission('expenses.pay') then raise exception 'Access denied'; end if;
  select * into request_row from public.expense_requests where id=p_request_id and status in ('approved','payment_processing','paid') for update;
  if request_row.id is null then raise exception 'Request is not approved for payment'; end if;
  select coalesce(sum(amount),0) into paid_total from public.expense_payments where expense_request_id=p_request_id;
  if p_amount<=0 or paid_total+p_amount>request_row.approved_amount then raise exception 'Payment exceeds unpaid balance %',request_row.approved_amount-paid_total; end if;
  insert into public.expense_payments(expense_request_id,payment_code,payment_date,payment_method,amount,bank_name,transaction_reference,recipient_name,paid_by,attachment)
  values(p_request_id,'PAY-'||extract(year from p_payment_date)::integer||'-'||lpad(nextval('public.expense_payment_code_sequence')::text,6,'0'),p_payment_date,p_method,p_amount,nullif(p_bank_name,''),nullif(p_reference,''),p_recipient,auth.uid(),p_attachment) returning * into payment;
  paid_total := paid_total+p_amount;
  update public.expense_requests set amount_received=paid_total,status=case when paid_total=approved_amount then 'paid' else 'payment_processing' end,
    paid_at=case when paid_total=approved_amount then now() else paid_at end,updated_by=auth.uid() where id=p_request_id;
  return payment;
end $$;

create or replace function public.sync_expense_actual() returns trigger language plpgsql security definer set search_path = public as $$
declare request_id uuid:=coalesce(new.expense_request_id,old.expense_request_id); total numeric;
begin
  select coalesce(sum(amount),0) into total from public.expense_items where expense_request_id=request_id;
  update public.expense_requests set actual_amount=total,returned_amount=greatest(amount_received-total,0),updated_by=auth.uid() where id=request_id and status<>'completed';
  return coalesce(new,old);
end $$;
create trigger expense_items_sync_actual after insert or update or delete on public.expense_items for each row execute function public.sync_expense_actual();

create or replace function public.complete_expense_request(p_request_id uuid) returns public.expense_requests
language plpgsql security definer set search_path = public as $$
declare request_row public.expense_requests; budget_row public.provincial_budgets; item_count integer; result public.expense_requests;
begin
  if not public.has_permission('expenses.complete') then raise exception 'Access denied'; end if;
  select * into request_row from public.expense_requests where id=p_request_id and status='paid' for update;
  if request_row.id is null then raise exception 'Only fully paid requests can be completed'; end if;
  select count(*) into item_count from public.expense_items where expense_request_id=p_request_id and attachment is not null;
  if item_count=0 then raise exception 'At least one supported expense item is required'; end if;
  if request_row.actual_amount>request_row.approved_amount and not public.has_permission('expenses.override_limit') then raise exception 'Actual expense exceeds approved amount'; end if;
  select * into budget_row from public.provincial_budgets where fiscal_year=extract(year from request_row.request_date)::integer and province_id=request_row.province_id and project_id=request_row.project_id and expense_category_id=request_row.expense_category_id for update;
  update public.provincial_budgets set committed_amount=greatest(committed_amount-request_row.approved_amount,0),actual_expense_amount=actual_expense_amount+request_row.actual_amount,updated_by=auth.uid() where id=budget_row.id;
  update public.expense_requests set status='completed',returned_amount=amount_received-actual_amount,completed_at=now(),updated_by=auth.uid() where id=p_request_id returning * into result;
  return result;
end $$;

create or replace function public.audit_expense_change() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.expense_audit_logs(user_id,action,module,record_id,old_values,new_values)
  values(auth.uid(),lower(tg_op),tg_table_name,coalesce(new.id,old.id),case when tg_op='INSERT' then null else to_jsonb(old) end,case when tg_op='DELETE' then null else to_jsonb(new) end);
  return coalesce(new,old);
end $$;
