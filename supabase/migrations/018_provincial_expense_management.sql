-- Provincial Expense Management: budgets, approvals, payments, actuals and closure.

create sequence if not exists public.expense_request_code_sequence start 1;
create sequence if not exists public.expense_payment_code_sequence start 1;

create table public.projects (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.expense_categories (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.approval_rules (
  id bigint generated by default as identity primary key,
  name text not null,
  min_amount numeric(16,2) not null default 0 check (min_amount >= 0),
  max_amount numeric(16,2) check (max_amount is null or max_amount >= min_amount),
  approval_level integer not null check (approval_level > 0),
  approver_role text not null references public.app_roles(key) on update cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(min_amount, max_amount, approval_level)
);

create table public.provincial_budgets (
  id uuid primary key default gen_random_uuid(),
  fiscal_year integer not null check (fiscal_year between 2000 and 2200),
  province_id bigint not null references public.provinces(id) on delete restrict,
  project_id bigint not null references public.projects(id) on delete restrict,
  expense_category_id bigint not null references public.expense_categories(id) on delete restrict,
  approved_amount numeric(16,2) not null check (approved_amount >= 0),
  revised_amount numeric(16,2) not null default 0,
  committed_amount numeric(16,2) not null default 0 check (committed_amount >= 0),
  actual_expense_amount numeric(16,2) not null default 0 check (actual_expense_amount >= 0),
  remaining_amount numeric(16,2) generated always as (approved_amount + revised_amount - committed_amount - actual_expense_amount) stored,
  status text not null default 'active' check (status in ('draft','active','closed','cancelled')),
  created_by uuid not null references public.profiles(id) on delete restrict default auth.uid(),
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(fiscal_year, province_id, project_id, expense_category_id),
  check (approved_amount + revised_amount >= 0)
);

create table public.expense_requests (
  id uuid primary key default gen_random_uuid(),
  request_code text not null unique,
  request_date date not null default current_date,
  province_id bigint not null references public.provinces(id) on delete restrict,
  project_id bigint not null references public.projects(id) on delete restrict,
  expense_category_id bigint not null references public.expense_categories(id) on delete restrict,
  purpose text not null check (char_length(trim(purpose)) between 5 and 2000),
  requested_amount numeric(16,2) not null check (requested_amount > 0),
  approved_amount numeric(16,2) not null default 0 check (approved_amount >= 0),
  amount_received numeric(16,2) not null default 0 check (amount_received >= 0),
  actual_amount numeric(16,2) not null default 0 check (actual_amount >= 0),
  returned_amount numeric(16,2) not null default 0 check (returned_amount >= 0),
  status text not null default 'draft' check (status in ('draft','submitted','under_review','returned','approved','rejected','payment_processing','paid','completed','cancelled')),
  requested_by uuid not null references public.profiles(id) on delete restrict default auth.uid(),
  submitted_at timestamptz,
  approved_at timestamptz,
  paid_at timestamptz,
  completed_at timestamptz,
  created_by uuid not null references public.profiles(id) on delete restrict default auth.uid(),
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.expense_approvals (
  id uuid primary key default gen_random_uuid(),
  expense_request_id uuid not null references public.expense_requests(id) on delete cascade,
