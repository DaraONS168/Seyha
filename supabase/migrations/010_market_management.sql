create or replace function public.audit_market_change() returns trigger
language plpgsql security definer set search_path = public as $$
declare action_name text;
begin
  action_name := case
    when tg_op = 'INSERT' then 'created'
    when old.deleted_at is null and new.deleted_at is not null then 'deleted'
    when old.deleted_at is not null and new.deleted_at is null then 'restored'
    else 'updated'
  end;
  insert into public.market_audit_logs(market_id, actor_id, action, old_values, new_values)
  values(coalesce(new.id, old.id), auth.uid(), action_name,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    case when tg_op = 'DELETE' then null else to_jsonb(new) end);
  return new;
end $$;

create trigger markets_audit after insert or update on public.markets
for each row execute function public.audit_market_change();

create or replace function public.market_statistics() returns jsonb
language sql stable security invoker set search_path = public as $$
  select jsonb_build_object(
    'total', count(*),
    'active', count(*) filter (where status = 'active'),
    'inactive', count(*) filter (where status = 'inactive'),
    'under_construction', count(*) filter (where status = 'under_construction'),
    'closed', count(*) filter (where status = 'closed'),
    'public_markets', count(*) filter (where market_type_id = (select id from public.market_types where code = 'public_market')),
    'total_stalls', coalesce(sum(total_stalls), 0),
    'occupied_stalls', coalesce(sum(occupied_stalls), 0),
    'trader_count', coalesce(sum(trader_count), 0)
  ) from public.markets where deleted_at is null;
$$;

