-- Market Management module: lookup data, markets, auditing, storage and RLS.

create sequence if not exists public.market_code_sequence start 1;

create table public.provinces (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9]{2,10}$'),
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.districts (
  id bigint generated by default as identity primary key,
  province_id bigint not null references public.provinces(id) on delete restrict,
  code text not null unique,
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.communes (
  id bigint generated by default as identity primary key,
  district_id bigint not null references public.districts(id) on delete restrict,
  code text not null unique,
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.villages (
  id bigint generated by default as identity primary key,
  commune_id bigint not null references public.communes(id) on delete restrict,
  code text not null unique,
  name_kh text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.market_types (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z][a-z0-9_]{2,39}$'),
  name_kh text not null,
  name_en text not null unique,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.markets (
  id uuid primary key default gen_random_uuid(),
  market_code text not null unique,
  name_kh text not null check (char_length(trim(name_kh)) between 2 and 200),
  name_en text check (name_en is null or char_length(trim(name_en)) between 2 and 200),
  market_type_id bigint not null references public.market_types(id) on delete restrict,
  status text not null default 'active' check (status in ('active','inactive','under_construction','closed')),
  opening_date date,
  province_id bigint not null references public.provinces(id) on delete restrict,
  district_id bigint not null references public.districts(id) on delete restrict,
  commune_id bigint not null references public.communes(id) on delete restrict,
  village_id bigint references public.villages(id) on delete restrict,
  street text,
  full_address text,
  latitude numeric(10,7) not null check (latitude between -90 and 90),
  longitude numeric(10,7) not null check (longitude between -180 and 180),
  google_map_url text,
  manager_name text,
  phone text check (phone is null or phone ~ '^(\\+?855|0)[1-9][0-9]{7,8}$'),
  email text check (email is null or email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\\.[A-Z]{2,}$'),
  opening_time time,
  closing_time time,
  total_stalls integer not null default 0 check (total_stalls >= 0),
  occupied_stalls integer not null default 0 check (occupied_stalls >= 0 and occupied_stalls <= total_stalls),
  trader_count integer not null default 0 check (trader_count >= 0),
  market_size numeric(12,2) check (market_size is null or market_size >= 0),
  description text,
  image text,
  created_by uuid not null references public.profiles(id) on delete restrict default auth.uid(),
  updated_by uuid references public.profiles(id) on delete set null,
  deleted_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  check (closing_time is null or opening_time is null or closing_time > opening_time)
);

create table public.market_audit_logs (
  id uuid primary key default gen_random_uuid(),
  market_id uuid not null,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null check (action in ('created','updated','deleted','restored')),
  old_values jsonb,
  new_values jsonb,
  created_at timestamptz not null default now()
);

